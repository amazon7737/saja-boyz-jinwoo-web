import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const origin = 'http://localhost:3821';
const key = 'hh:recent-searches:v1';
(async () => {
  const browser = await chromium.launch({headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  const page = await browser.newPage({viewport: {width: 393, height: 852}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const recent = () => page.getByRole('region', {name: '최근 검색', exact: true});
  const stored = () => page.evaluate(k => JSON.parse(localStorage.getItem(k) || '[]'), key);
  const reset = async () => {
    await page.getByRole('link', {name: '검색어 초기화'}).click();
    await page.waitForURL(origin + '/search');
    await recent().waitFor();
  };
  const submit = async keyword => {
    await page.getByRole('searchbox', {name: '기사 키워드 검색'}).fill(keyword);
    await page.getByRole('button', {name: '검색', exact: true}).click();
    await page.waitForURL(u => u.pathname === '/search' && u.searchParams.get('q')?.trim() === keyword.trim());
    await page.getByRole('region', {name: '기사 검색 결과'}).waitFor();
    await page.waitForFunction(({k, q}) => JSON.parse(localStorage.getItem(k) || '[]')[0] === q, {k: key, q: keyword.trim()});
  };
  await page.goto(origin + '/search');
  await recent().waitFor();
  await page.evaluate(k => localStorage.removeItem(k), key);
  await page.reload();
  await recent().getByText('최근 검색어가 없어요').waitFor();
  await submit('서울 & 화재');
  assert.equal(await recent().count(), 0);
  await reset();
  const first = recent().getByRole('link', {name: '서울 & 화재'});
  assert.equal(await first.getAttribute('href'), '/search?q=' + encodeURIComponent('서울 & 화재'));
  await first.click();
  await page.waitForURL(u => u.searchParams.get('q') === '서울 & 화재');
  await page.getByRole('region', {name: '기사 검색 결과'}).waitFor();
  assert.deepEqual(await stored(), ['서울 & 화재']);
  await reset();
  await page.getByRole('link', {name: /대형화재/}).click();
  await page.waitForFunction(k => JSON.parse(localStorage.getItem(k) || '[]')[0] === '대형화재', key);
  await reset();
  await submit('서울 & 화재');
  assert.deepEqual(await stored(), ['서울 & 화재', '대형화재']);
  await reset();
  await page.screenshot({path: '/tmp/recent-search-normal-393.png'});
  const borders = await recent().locator('li').first().evaluate(el => {
    const s = getComputedStyle(el);
    return [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth];
  });
  assert.deepEqual(borders, ['0px', '0px', '1px', '0px']);
  const countBefore = (await (await fetch('http://127.0.0.1:3820/requests')).json()).length;
  await recent().getByRole('button', {name: '서울 & 화재 삭제', exact: true}).click();
  assert.deepEqual(await stored(), ['대형화재']);
  assert.equal(page.url(), origin + '/search');
  assert.equal((await (await fetch('http://127.0.0.1:3820/requests')).json()).length, countBefore);
  await page.reload();
  await recent().getByRole('link', {name: '대형화재'}).waitFor();
  assert.equal(await recent().getByRole('link', {name: '서울 & 화재'}).count(), 0);
  await page.goto(origin + '/search?q=' + encodeURIComponent('오류검색'));
  await page.getByRole('alert').filter({hasText: '검색 결과를 불러오지 못했어요'}).waitFor();
  await page.waitForFunction(k => JSON.parse(localStorage.getItem(k) || '[]')[0] === '오류검색', key);
  await reset();
  await page.evaluate(k => localStorage.setItem(k, JSON.stringify([String.fromCharCode(0xd800), '정상 검색어', String.fromCharCode(0xdc00), '🔥 화재'])), key);
  await page.reload();
  await recent().getByRole('link', {name: '🔥 화재', exact: true}).waitFor();
  assert.deepEqual(await recent().getByRole('link').allTextContents().then(v => v.map(t => t.replace('🕒', '').trim())), ['정상 검색어', '🔥 화재']);
  assert.equal(await recent().getByRole('link', {name: '🔥 화재', exact: true}).getAttribute('href'), '/search?q=' + encodeURIComponent('🔥 화재'));
  await submit('소방');
  assert.deepEqual(await stored(), ['소방', '정상 검색어', '🔥 화재']);
  await reset();
  const long = '긴검색어'.repeat(100);
  const malicious = '<img src=x onerror=alert(1)>';
  await page.evaluate(({k, values}) => localStorage.setItem(k, JSON.stringify(values)), {k: key, values: [long, malicious, ...Array.from({length: 12}, (_, i) => '기록 ' + i)]});
  await page.reload();
  await recent().getByRole('button', {name: long + ' 삭제'}).waitFor();
  assert.equal(await recent().getByRole('link').count(), 10);
  assert.equal(await recent().locator('img, script').count(), 0);
  await page.evaluate(k => localStorage.setItem(k, JSON.stringify(['  서울 소방서  ', '서울 소방서', '', 3, '서교동 화재'])), key);
  await page.reload();
  await recent().getByRole('link', {name: '서울 소방서', exact: true}).waitFor();
  assert.deepEqual(await recent().getByRole('link').allTextContents().then(v => v.map(t => t.replace('🕒', '').trim())), ['서울 소방서', '서교동 화재']);
  await page.evaluate(({k, values}) => localStorage.setItem(k, JSON.stringify(values)), {k: key, values: [long, malicious, ...Array.from({length: 12}, (_, i) => '기록 ' + i)]});
  await page.reload();
  await recent().getByRole('button', {name: long + ' 삭제'}).waitFor();
  for (const width of [320, 393, 1280]) {
    await page.setViewportSize({width, height: 852});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const button = await recent().getByRole('button', {name: long + ' 삭제'}).boundingBox();
    assert(button && button.x >= 0 && button.x + button.width <= width);
    await page.screenshot({path: '/tmp/recent-search-' + width + '.png'});
  }
  const blocked = await browser.newContext();
  await blocked.addInitScript(() => {
    Object.defineProperty(Storage.prototype, 'getItem', {value() {throw new DOMException('blocked', 'SecurityError');}});
    Object.defineProperty(Storage.prototype, 'setItem', {value() {throw new DOMException('full', 'QuotaExceededError');}});
  });
  const unavailable = await blocked.newPage();
  unavailable.on('pageerror', e => errors.push(e.message));
  await unavailable.goto(origin + '/search?q=' + encodeURIComponent('화재'));
  await unavailable.getByRole('region', {name: '기사 검색 결과'}).waitFor();
  await unavailable.getByRole('link', {name: '검색어 초기화'}).click();
  await unavailable.getByRole('region', {name: '최근 검색'}).getByText('최근 검색어가 없어요').waitFor();
  await unavailable.getByRole('searchbox', {name: '기사 키워드 검색'}).fill('입력가능');
  assert.deepEqual(errors, []);
  console.log('PASS: real Chrome form/recommendation/recent link, dedupe, deletion without requests, reload persistence, failed search recording, text safety, max 10, 320/393/1280 widths, blocked storage, no pageerror');
  await browser.close();
})().catch(e => {console.error(e); process.exit(1);});
